"""Two hand-drawn pixel fonts: SMALL (capitals 6 px, lower case with descenders) and BOLD (capitals only, 9 px,
2 px strokes, for the words painted on the menu plaques)."""


def _glyphs(src, height):
    """Parses blocks of '<char>' followed by its rows; rows shorter than `height` are padded below."""
    out = {}
    for block in src.strip().split("\n\n"):
        lines = block.split("\n")
        ch, rows = lines[0].strip("'"), [r.strip() for r in lines[1:]]
        w = len(rows[0])
        assert all(len(r) == w for r in rows), ch
        out[ch] = rows + ["." * w] * (height - len(rows))
    return out


