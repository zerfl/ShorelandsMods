def measure(s, font, gap=1):
    return sum(len(font[ch][0]) for ch in s) + gap * (len(s) - 1)


def text(canvas, x, y, s, font, colour, shadow=None, gap=1):
    """Draws `s` with its top-left at (x, y); `shadow` is drawn 1 px below first. Returns the width."""
    for ox, oy, c in ([(0, 1, shadow)] if shadow else []) + [(0, 0, colour)]:
        cx = x
        for ch in s:
            g = font[ch]
            for gy, row in enumerate(g):
                for gx, p in enumerate(row):
                    if p == "#":
                        canvas.set(cx + gx + ox, y + gy + oy, c)
            cx += len(g[0]) + gap
    return measure(s, font, gap)
